/**
 * The heavy rule above the two signatures of the regulations: Word's
 * "dash-dot stroked" border, 3 pt thick. Word draws it as slanted strokes, a
 * long group then a short one. Drawn here to the same pattern; the exact
 * strokes are Word's own and were not seen printed.
 */
export function DashDotRule({ widthMm }: { widthMm: number }) {
  const unit = 9.2; // one long group and one short group, in millimetres
  const strokes = [0, 0.75, 1.5, 2.25, 3, 3.75, 4.5, 6.6];
  const count = Math.ceil(widthMm / unit);
  return (
    <svg
      width={`${widthMm}mm`}
      height="1.06mm"
      viewBox={`0 0 ${widthMm} 1.06`}
      preserveAspectRatio="none"
      aria-hidden
      style={{ display: "block" }}
    >
      {Array.from({ length: count }, (_, group) =>
        strokes.map((at) => {
          const x = group * unit + at;
          return <path key={`${group}-${at}`} d={`M${x} 1.06 L${x + 0.5} 0 H${x + 1} L${x + 0.5} 1.06Z`} fill="#000" />;
        }),
      )}
    </svg>
  );
}

const ZERO_WIDTH_JOINER = "\u200d";

/** A stretch of a label, with the highlight Word prints behind it, if any. */
export interface LabelRun {
  text: string;
  background?: string;
}

/**
 * One of his labels that he stretched to the width of its cell with the
 * stretching character: «اللقــــــــــب والاســـــــــــــــــــــــــم».
 *
 * With his font on the PC the label is printed as he typed it, and it fills the
 * cell because he typed it to. The font bundled with the program draws that
 * character at another width, so the same string would run past its cell or
 * onto more lines and change the height of its row. There, each run of
 * stretching characters is drawn as what it is, a stroke along the baseline,
 * as long as the cell allows: the letters keep their size and their joins, and
 * the label fills its cell on one line as on his sheet.
 *
 * `raw` is the label as he typed it, or its runs when part of it is
 * highlighted.
 */
export function StretchedLabel({
  raw,
  face,
  pt,
  ...type
}: { raw: string | readonly LabelRun[]; face: SheetFont; pt: number } & HisTypeOptions) {
  const style = hisType(face, pt, type);
  const runs: readonly LabelRun[] = typeof raw === "string" ? [{ text: raw }] : raw;
  const elastic = !faceInstalled(face) && runs.some((run) => run.text.includes(TATWEEL));

  // Cut at every run of stretching characters, keeping each piece's highlight.
  const pieces = runs.flatMap((run) =>
    (elastic ? run.text.split(new RegExp(`(${TATWEEL}+)`)) : [run.text])
      .filter((text) => text !== "")
      .map((text) => ({ text, background: run.background })),
  );
  // Letters cut apart must still join: tell each side of a cut to reach for the other.
  const joined = pieces.map((piece, index) => {
    const before = pieces[index - 1]?.text.at(-1);
    const after = pieces[index + 1]?.text[0];
    const joinsBefore = before !== undefined && before !== " " && piece.text[0] !== " ";
    const joinsAfter = after !== undefined && after !== " " && piece.text.at(-1) !== " ";
    return {
      ...piece,
      shown: (joinsBefore ? ZERO_WIDTH_JOINER : "") + piece.text + (joinsAfter ? ZERO_WIDTH_JOINER : ""),
    };
  });

  if (!elastic) {
    return (
      <span style={style}>
        {joined.map((piece, index) => (
          <span key={index} style={piece.background ? { background: piece.background } : undefined}>
            {pieces.length > 1 ? piece.shown : piece.text}
          </span>
        ))}
      </span>
    );
  }

  return (
    <span style={{ ...style, display: "flex", width: "100%", whiteSpace: "pre" }}>
      {joined.map((piece, index) =>
        piece.text.startsWith(TATWEEL) ? (
          // The stroke: more of it than can ever be needed, cut to the room there is.
          <span
            key={index}
            style={{
              flex: `${piece.text.length} 1 0`,
              minWidth: 0,
              overflow: "hidden",
              marginInline: "-0.12mm",
              background: piece.background,
            }}
          >
            {TATWEEL.repeat(80)}
          </span>
        ) : (
          <span key={index} style={{ flex: "none", background: piece.background }}>
            {piece.shown}
          </span>
        ),
      )}
    </span>
  );
}
